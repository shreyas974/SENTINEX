
const riskScore = document.getElementById("riskScore");
const systemStatus = document.getElementById("systemStatus");
const alertCount = document.getElementById("alertCount");
const alertTable = document.getElementById("alertTable");
const simulateButton = document.getElementById("simulateButton");
const canvas = document.getElementById("riskChart");
const ctx = canvas.getContext("2d");

let scores = [12, 18, 15, 22, 20, 30, 25, 18];
let totalAlerts = 0;

function drawChart() {
    const width = canvas.clientWidth;
    const height = 220;

    canvas.width = width;
    canvas.height = height;

    ctx.clearRect(0, 0, width, height);

    // Draw horizontal grid lines
    ctx.strokeStyle = "#e2e8f0";
    ctx.lineWidth = 1;

    for (let i = 0; i <= 4; i++) {
        const y = 15 + (height - 35) * i / 4;

        ctx.beginPath();
        ctx.moveTo(35, y);
        ctx.lineTo(width - 10, y);
        ctx.stroke();

        ctx.fillStyle = "#64748b";
        ctx.font = "11px Arial";
        ctx.fillText(100 - i * 25, 3, y + 4);
    }

    // Draw anomaly score line
    const chartWidth = width - 50;
    const chartHeight = height - 35;

    ctx.beginPath();
    ctx.strokeStyle = "#0284c7";
    ctx.lineWidth = 3;

    scores.forEach((score, index) => {
        const x = 35 + (index / Math.max(scores.length - 1, 1))
            * chartWidth;
        const y = 15 + ((100 - score) / 100) * chartHeight;

        if (index === 0) {
            ctx.moveTo(x, y);
        } else {
            ctx.lineTo(x, y);
        }
    });

    ctx.stroke();
}

function addAlert(score) {
    const time = new Date().toLocaleTimeString();

    const row = document.createElement("tr");

    const timeCell = document.createElement("td");
    timeCell.textContent = time;

    const eventCell = document.createElement("td");
    eventCell.textContent = "Unusual activity detected";

    const riskCell = document.createElement("td");
    riskCell.textContent = score + "%";

    const statusCell = document.createElement("td");
    statusCell.textContent = "Review required";

    row.append(timeCell, eventCell, riskCell, statusCell);
    alertTable.prepend(row);

    totalAlerts++;
    alertCount.textContent = totalAlerts;
}

function simulateEvent() {
    // Demo score only; not generated by the actual ML model.
    const score = Math.floor(Math.random() * 101);

    scores.push(score);

    if (scores.length > 12) {
        scores.shift();
    }

    riskScore.textContent = score + "%";

    if (score >= 60) {
        systemStatus.textContent = "High Risk";
        systemStatus.className = "value warning";
        addAlert(score);
    } else {
        systemStatus.textContent = "Normal";
        systemStatus.className = "value safe";
    }

    drawChart();
}

simulateButton.addEventListener("click", simulateEvent);

window.addEventListener("resize", drawChart);

drawChart();
